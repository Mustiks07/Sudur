/// ASR model offered by the prototype settings.
enum PrototypeModelChoice {
  /// Larger model from the pinned Hugging Face revision.
  small,

  /// Smaller model for slower phones.
  tiny,
}

/// Download and verification progress for first-run resources.
final class PrototypeDownloadProgress {
  /// Creates a progress snapshot.
  const new({
    required this.completedBytes,
    required this.totalBytes,
    required this.resourceName,
  });

  /// Bytes already verified or downloaded.
  final int completedBytes;

  /// Total known bytes for the selected models, fonts, licenses, and content.
  final int totalBytes;

  /// Non-localized technical resource name.
  final String resourceName;

  /// Fraction in the inclusive 0–1 range.
  double get fraction => totalBytes == 0 ? 0 : completedBytes / totalBytes;
}

/// What is already installed; `null` for what is not.
final class PrototypeInstalledFiles {
  /// Creates the paths.
  const new({
    required this.modelDirectory,
    required this.vadModelPath,
    required this.contentPath,
    required this.fontDirectory,
  });

  /// ASR model package directory.
  final String? modelDirectory;

  /// Silero VAD model.
  final String? vadModelPath;

  /// Prototype content (pages 582–583 with layout).
  final String? contentPath;

  /// Fonts of pages 582–583.
  final String? fontDirectory;

  /// Whether reading with voice is possible.
  bool get voiceReady => modelDirectory != null && vadModelPath != null;
}

