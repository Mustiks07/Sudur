/// ASR model offered by the prototype settings.
enum PrototypeModelChoice {
  /// Larger model from the pinned Hugging Face revision.
  small,

  /// Smaller model for slower phones.
  tiny,
}

/// Download and verification progress for first-run resources.
final class PrototypeDownloadProgress {
  /// Creates a progress snapshot.
  const new({
    required this.completedBytes,
    required this.totalBytes,
    required this.resourceName,
  });

  /// Bytes already verified or downloaded.
  final int completedBytes;

  /// Total known bytes for the selected model, fonts, and content.
  final int totalBytes;

  /// Non-localized technical resource name.
  final String resourceName;

  /// Fraction in the inclusive 0–1 range.
  double get fraction => totalBytes == 0 ? 0 : completedBytes / totalBytes;
}

/// Verified local paths consumed by the prototype repository.
final class PrototypeResources {
  /// Creates installed resource paths.
  const new({
    required this.contentPath,
    required this.fontDirectory,
    required this.modelDirectory,
  });

  /// Canonical content JSON generated by `content_build`.
  final String contentPath;

  /// Directory containing `p582.ttf` and `p583.ttf`.
  final String fontDirectory;

  /// Complete ASR package understood by `asr_sherpa`.
  final String modelDirectory;
}

/// Downloads pinned prototype resources and verifies every downloaded byte.
final class PrototypeAssetInstaller {
  /// Creates the installer.
  new(this._platform, {HttpClient? httpClient})
    : _httpClient = httpClient ?? HttpClient();

  final PrototypePlatformService _platform;
  final HttpClient _httpClient;

  /// Ensures content, both page fonts, and [model] are installed.
  Future<PrototypeResources> install(
    PrototypeModelChoice model, {
    required void Function(PrototypeDownloadProgress progress) onProgress,
  }) async {
    final root = Directory(await _platform.applicationDirectory());
    await root.create(recursive: true);
    final modelManifest = _models[model];
    if (modelManifest == null) {
      throw StateError('The selected model has no resource manifest.');
    }
    final resources = <_RemoteResource>[
      _content,
      ..._fonts,
      ...modelManifest.files,
    ];
    final total = resources.fold<int>(0, (sum, item) => sum + item.size);
    var completed = 0;

    for (final resource in resources) {
      final target = File('${root.path}/${resource.relativePath}');
      await _ensureResource(
        resource,
        target,
        onBytes: (received) {
          onProgress(
            PrototypeDownloadProgress(
              completedBytes: completed + received,
              totalBytes: total,
              resourceName: resource.displayName,
            ),
          );
        },
      );
      completed += resource.size;
      onProgress(
        PrototypeDownloadProgress(
          completedBytes: completed,
          totalBytes: total,
          resourceName: resource.displayName,
        ),
      );
    }

    final modelDirectory = Directory(
      '${root.path}/models/${modelManifest.directoryName}',
    );
    await _writeModelMetadata(modelDirectory, modelManifest);
    return PrototypeResources(
      contentPath: '${root.path}/content/content_p582_583.json',
      fontDirectory: '${root.path}/fonts',
      modelDirectory: modelDirectory.path,
    );
  }

  Future<void> _ensureResource(
    _RemoteResource resource,
    File target, {
    required void Function(int receivedBytes) onBytes,
  }) async {
    if (await _isValid(target, resource)) {
      onBytes(resource.size);
      return;
    }
    await target.parent.create(recursive: true);
    final temporary = File('${target.path}.download');
    if (await temporary.exists()) await temporary.delete();
    try {
      final request = await _httpClient.getUrl(Uri.parse(resource.url));
      final response = await request.close();
      if (response.statusCode != HttpStatus.ok) {
        throw HttpException(
          'Download failed with HTTP ${response.statusCode}.',
          uri: Uri.parse(resource.url),
        );
      }
      final sink = temporary.openWrite();
      var received = 0;
      await for (final chunk in response) {
        sink.add(chunk);
        received += chunk.length;
        onBytes(received);
      }
      await sink.close();
      if (!await _isValid(temporary, resource)) {
        throw StateError(
          '${resource.displayName} failed SHA-256 verification.',
        );
      }
      if (await target.exists()) await target.delete();
      await temporary.rename(target.path);
    } on Object {
      if (await temporary.exists()) await temporary.delete();
      rethrow;
    }
  }

  Future<bool> _isValid(File file, _RemoteResource resource) async {
    if (!await file.exists() || await file.length() != resource.size) {
      return false;
    }
    final digest = await sha256.bind(file.openRead()).first;
    return digest.toString() == resource.sha256;
  }

  Future<void> _writeModelMetadata(
    Directory directory,
    _ModelManifest manifest,
  ) async {
    final spellingFile = File('${directory.path}/spelling.json');
    final Object? decoded = jsonDecode(await spellingFile.readAsString());
    if (decoded is! Map<String, Object?>) {
      throw const FormatException('spelling.json must contain an object.');
    }
    final replacements = <Map<String, String>>[];
    for (final entry in decoded.entries) {
      final replacement = entry.value;
      if (entry.key.isEmpty || replacement is! String) {
        throw const FormatException('spelling.json has an invalid entry.');
      }
      replacements.add(<String, String>{'from': entry.key, 'to': replacement});
    }
    await _writeJson(
      File('${directory.path}/normalizer.json'),
      <String, Object?>{
        'id': manifest.normalizerId,
        'nfc': true,
        'removeRanges': <Object?>[],
        'replace': replacements,
        'wordSeparator': ' ',
      },
    );
    await _writeJson(File('${directory.path}/thresholds.json'), _thresholds);
    await _writeJson(File('${directory.path}/model.json'), <String, Object?>{
      'modelId': manifest.modelId,
      'version': manifest.version,
      'output': 'uthmaniLettersNoDiacritics',
      'isStreaming': false,
      'hasTokenTimes': true,
      'sampleRate': 16000,
      'minRamMb': manifest.minRamMb,
      'license': 'MIT',
      'normalizerId': manifest.normalizerId,
      'modelSizeBytes': manifest.modelSize,
      'tokensSizeBytes': manifest.tokensSize,
      'modelSha256': manifest.modelSha256,
      'tokensSha256': manifest.tokensSha256,
    });
  }

  Future<void> _writeJson(File file, Map<String, Object?> value) => file
      .writeAsString('${const JsonEncoder.withIndent('  ').convert(value)}\n');
}

final class _RemoteResource {
  const new({
    required this.displayName,
    required this.relativePath,
    required this.url,
    required this.sha256,
    required this.size,
  });

  final String displayName;
  final String relativePath;
  final String url;
  final String sha256;
  final int size;
}

final class _ModelManifest {
  const new({
    required this.directoryName,
    required this.modelId,
    required this.version,
    required this.normalizerId,
    required this.minRamMb,
    required this.modelSize,
    required this.tokensSize,
    required this.modelSha256,
    required this.tokensSha256,
    required this.files,
  });

  final String directoryName;
  final String modelId;
  final String version;
  final String normalizerId;
  final int minRamMb;
  final int modelSize;
  final int tokensSize;
  final String modelSha256;
  final String tokensSha256;
  final List<_RemoteResource> files;
}

