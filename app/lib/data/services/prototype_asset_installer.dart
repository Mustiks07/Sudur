List<_RemoteResource> _modelFiles({
  required String name,
  required String revision,
  required String modelSha256,
  required int modelSize,
}) {
  final base = 'https://huggingface.co/Abdou/quran-asr-$name/resolve/$revision';
  final directory = 'models/quran-asr-$name';
  return <_RemoteResource>[
    _RemoteResource(
      displayName: '$name-model',
      relativePath: '$directory/model.int8.onnx',
      url: '$base/model.int8.onnx',
      sha256: modelSha256,
      size: modelSize,
    ),
    for (final entry in _sharedModelFiles.entries)
      _RemoteResource(
        displayName: '$name-${entry.key}',
        relativePath: '$directory/${entry.key}',
        url: '$base/${entry.key}',
        sha256: entry.value.sha256,
        size: entry.value.size,
      ),
  ];
}

