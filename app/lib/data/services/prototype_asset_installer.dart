/// Verified local paths consumed by the prototype repository.
final class PrototypeResources {
  /// Creates installed resource paths.
  const new({
    required this.contentPath,
    required this.fontDirectory,
    required this.modelDirectory,
    required this.vadModelPath,
  });

  /// Canonical content JSON generated by `content_build`.
  final String contentPath;

  /// Directory containing `p582.ttf` and `p583.ttf`.
  final String fontDirectory;

  /// Complete ASR package understood by `asr_sherpa`.
  final String modelDirectory;

  /// Verified Silero VAD model shared by microphone and WAV capture.
  final String vadModelPath;
